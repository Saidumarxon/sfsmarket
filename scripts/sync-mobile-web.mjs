/**
 * Copies the static storefront into www/ for Capacitor (iOS + Android).
 * Set EMIRATE_SITE_URL for NBU API proxy (e.g. https://emirateco.uz).
 * Set CAPACITOR_SERVER_URL to load the live site instead of bundled files.
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");
const www = path.join(root, "www");

const HTML_PAGES = ["index.html", "catalog.html", "product.html", "checkout.html", "login.html", "auth-callback.html"];

const JS_FILES = [
  "app.js",
  "catalog.js",
  "product.js",
  "checkout.js",
  "common.js",
  "theme.js",
  "translations.js",
  "emirate-exchange.js",
  "emirate-supabase-api.js",
  "emirate-image-search.js",
  "emirate-seo.js",
  "emirate-seo-config.js",
  "emirate-auth.js",
  "supabase-config.prod.js",
];

const STATIC_FILES = ["mobile.css", "manifest.webmanifest"];

function rmDir(dir) {
  if (fs.existsSync(dir)) fs.rmSync(dir, { recursive: true, force: true });
}

function copyFile(src, dest) {
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.copyFileSync(src, dest);
}

function copyDir(srcDir, destDir) {
  if (!fs.existsSync(srcDir)) return;
  fs.mkdirSync(destDir, { recursive: true });
  for (const entry of fs.readdirSync(srcDir, { withFileTypes: true })) {
    const src = path.join(srcDir, entry.name);
    const dest = path.join(destDir, entry.name);
    if (entry.isDirectory()) copyDir(src, dest);
    else copyFile(src, dest);
  }
}

function writeMobileConfig() {
  const siteUrl = (process.env.EMIRATE_SITE_URL || "https://emirateco.uz").replace(/\/+$/, "");
  const contents = `/** Generated by scripts/sync-mobile-web.mjs */
(function () {
  window.emirateApiBase = ${JSON.stringify(siteUrl)};
})();
`;
  fs.writeFileSync(path.join(www, "mobile-config.js"), contents, "utf8");
  fs.writeFileSync(path.join(root, "mobile-config.js"), contents, "utf8");
}

function writeCapacitorConfig() {
  const serverUrl = (process.env.CAPACITOR_SERVER_URL || "").trim().replace(/\/+$/, "");
  const config = {
    appId: "uz.emirateco.shop",
    appName: "Emirate Co",
    webDir: "www",
    bundledWebRuntime: false,
    server: {
      androidScheme: "https",
      iosScheme: "https",
    },
    plugins: {
      SplashScreen: {
        launchShowDuration: 2000,
        launchAutoHide: true,
        backgroundColor: "#0f172a",
        showSpinner: false,
      },
    },
  };

  if (serverUrl) {
    config.server.url = serverUrl;
    config.server.cleartext = false;
    console.log("[mobile] Capacitor remote URL:", serverUrl);
  }

  fs.writeFileSync(path.join(root, "capacitor.config.json"), JSON.stringify(config, null, 2) + "\n", "utf8");
}

console.log("[mobile] Preparing www/ …");
rmDir(www);
fs.mkdirSync(www, { recursive: true });

for (const file of HTML_PAGES) {
  copyFile(path.join(root, file), path.join(www, file));
}

for (const file of JS_FILES) {
  copyFile(path.join(root, file), path.join(www, file));
}

copyFile(path.join(root, "supabase-config.prod.js"), path.join(www, "supabase-config.js"));
copyFile(path.join(root, "styles.css"), path.join(www, "styles.css"));
copyFile(path.join(root, "robots.txt"), path.join(www, "robots.txt"));
copyFile(path.join(root, "mobile", "mobile-bridge.js"), path.join(www, "mobile-bridge.js"));

for (const file of STATIC_FILES) {
  copyFile(path.join(root, "mobile", file), path.join(www, file));
}

copyDir(path.join(root, "images"), path.join(www, "images"));
copyDir(path.join(root, "mobile", "icons"), path.join(www, "icons"));

for (const file of STATIC_FILES) {
  copyFile(path.join(root, "mobile", file), path.join(root, file));
}
copyFile(path.join(root, "mobile", "mobile-bridge.js"), path.join(root, "mobile-bridge.js"));
copyDir(path.join(root, "mobile", "icons"), path.join(root, "icons"));

writeMobileConfig();
writeCapacitorConfig();

console.log("[mobile] www/ ready (" + HTML_PAGES.length + " pages)");
